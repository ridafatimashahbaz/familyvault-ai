/**
 * How many PDF pages the app reads per document. This caps *processing*, not
 * storage: the file is always kept whole and downloadable, but the OCR worker is
 * single and serialised, so reading a 300-page scan would block every other
 * upload for minutes. Pages beyond this are reported as unread.
 */
export const MAX_PDF_PAGES = 40;

/**
 * How many pages of a *scanned* PDF get OCR'd in one upload. Lower than
 * MAX_PDF_PAGES on purpose: a text layer is nearly free to read, while each
 * OCR page costs seconds and processing happens inside the upload request.
 */
export const MAX_OCR_PAGES = 12;

/** Stop OCR-ing further pages once this much time has been spent. */
export const OCR_TIME_BUDGET_MS = 60_000;

/**
 * Upper bound for a user-saved correction of the extracted text. Generous
 * because a hand-typed transcription of a long document is legitimate, but
 * still bounded: without a limit one request could store arbitrary amounts of
 * text per document.
 */
export const MAX_TEXT_EDIT_CHARS = 200_000;

