export type DocTypeDef = {
  key: string;
  label: string;
  category: CategoryKey;
  /** Lowercase phrases scored against OCR text. Longer phrases weigh more. */
  keywords: string[];
  /** Substrings matched against the uploaded file name. */
  filenameHints: string[];
  /** This type commonly carries an expiry date worth tracking. */
  hasExpiry: boolean;
  /** Document types that are effectively permanent once issued. */
  permanent?: boolean;
  /** Field labels the extractor should look for. */
  fields?: string[];
};

